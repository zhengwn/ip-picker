#[cfg(test)]
mod tests {
    use super::location;

    #[test]
    fn maps_core_regions_and_never_guesses_unknown_codes() {
        for (colo, region) in [
            ("HKG", "HK"),
            ("NRT", "JP"),
            ("KIX", "JP"),
            ("SIN", "SG"),
            ("SJC", "US"),
            ("FRA", "DE"),
            ("SYD", "AU"),
            ("ICN", "KR"),
            ("TPE", "TW"),
            ("LHR", "GB"),
            ("YYZ", "CA"),
            ("AMS", "NL"),
            ("CDG", "FR"),
            ("BOM", "IN"),
        ] {
            assert_eq!(location(colo).unwrap().0, region);
        }
        assert_eq!(location("ZZZ"), None);
        assert_eq!(location("nrt"), None);
    }
}
